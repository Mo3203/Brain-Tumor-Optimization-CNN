def true_and_pred(val_loader, model, device):
    model.eval()
    y_true, y_pred, y_scores = [], [], []

    with torch.no_grad():
        for images, labels in val_loader:
            images, labels = images.to(device), labels.to(device)

            outputs = model(images)
            # Auto-handle model output — sigmoid or softmax
            if outputs.shape[1] == 1:
                probs = torch.sigmoid(outputs)        # For binary (1 output)
                preds = (probs > 0.5).long().squeeze(1)
            else:
                probs = torch.softmax(outputs, dim=1) # For softmax (multi-class)
                preds = torch.argmax(probs, dim=1)

            y_true.append(labels.detach().cpu().numpy())
            y_pred.append(preds.detach().cpu().numpy())
            y_scores.append(probs.detach().cpu().numpy())

    y_true = np.concatenate(y_true)
    y_pred = np.concatenate(y_pred)
    y_scores = np.concatenate(y_scores)

    return y_true, y_pred, y_scores

